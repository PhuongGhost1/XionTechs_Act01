// Precomputes the point cloud the finale converges on. Run once when the logo changes:
//   node scripts/make-logo-points.mjs
// Reads public/concepts/command/logo-reversed.png, picks about MAX evenly spread opaque pixels and
// writes src/concepts/command/finale/logoPoints.js. A precomputed module is deterministic, instant
// and testable; sampling an image at runtime would not be (decode time, canvas tainting).
import { readFileSync, writeFileSync } from 'node:fs'
import { inflateSync } from 'node:zlib'

const SRC = 'public/concepts/command/logo-reversed.png'
const OUT = 'src/concepts/command/finale/logoPoints.js'
const MAX = 620
const ALPHA_MIN = 110

// Minimal PNG decoder: 8-bit RGBA, non-interlaced (what the logo is).
function decodePng(buf) {
  let o = 8
  let w = 0
  let h = 0
  const idat = []
  while (o < buf.length) {
    const len = buf.readUInt32BE(o)
    const type = buf.toString('ascii', o + 4, o + 8)
    const data = buf.subarray(o + 8, o + 8 + len)
    if (type === 'IHDR') {
      w = data.readUInt32BE(0)
      h = data.readUInt32BE(4)
      if (data[8] !== 8 || data[9] !== 6 || data[12] !== 0) throw new Error('expected 8-bit RGBA, non-interlaced')
    } else if (type === 'IDAT') idat.push(data)
    o += 12 + len
  }
  const raw = inflateSync(Buffer.concat(idat))
  const bpp = 4
  const stride = w * bpp
  const px = Buffer.alloc(h * stride)
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)]
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1))
    for (let x = 0; x < stride; x++) {
      const a = x >= bpp ? px[y * stride + x - bpp] : 0
      const b = y > 0 ? px[(y - 1) * stride + x] : 0
      const c = x >= bpp && y > 0 ? px[(y - 1) * stride + x - bpp] : 0
      let v = line[x]
      if (f === 1) v += a
      else if (f === 2) v += b
      else if (f === 3) v += (a + b) >> 1
      else if (f === 4) {
        const p = a + b - c
        const pa = Math.abs(p - a)
        const pb = Math.abs(p - b)
        const pc = Math.abs(p - c)
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c
      }
      px[y * stride + x] = v & 255
    }
  }
  return { w, h, px }
}

const { w, h, px } = decodePng(readFileSync(SRC))
const opaque = []
for (let i = 0; i < w * h; i++) if (px[i * 4 + 3] >= ALPHA_MIN) opaque.push(i)

// Even spread: find the smallest square cell size that gives at most MAX non-empty cells, then take
// the opaque pixel closest to each cell's mean. Even spacing keeps thin letters readable.
function pick(size) {
  const cols = Math.ceil(w / size)
  const cells = new Map()
  for (const i of opaque) {
    const x = i % w
    const y = (i / w) | 0
    const key = Math.floor(y / size) * cols + Math.floor(x / size)
    const c = cells.get(key) ?? { sx: 0, sy: 0, n: 0, m: [] }
    c.sx += x
    c.sy += y
    c.n++
    c.m.push(i)
    cells.set(key, c)
  }
  const out = []
  for (const c of cells.values()) {
    const mx = c.sx / c.n
    const my = c.sy / c.n
    let best = c.m[0]
    let bd = Infinity
    for (const i of c.m) {
      const d = ((i % w) - mx) ** 2 + (((i / w) | 0) - my) ** 2
      if (d < bd) {
        bd = d
        best = i
      }
    }
    out.push(best)
  }
  return out
}

let size = 1
let chosen = opaque
while (chosen.length > MAX) {
  size += 0.25
  chosen = pick(size)
}
chosen.sort((a, b) => a - b)

// Yellow where red clearly dominates blue (the X mark); white elsewhere.
const xs = []
const ys = []
let yellow = ''
for (const i of chosen) {
  xs.push(i % w)
  ys.push((i / w) | 0)
  const r = px[i * 4]
  const b = px[i * 4 + 2]
  yellow += r - b > 60 ? '1' : '0'
}

const body = `// GENERATED by scripts/make-logo-points.mjs from ${SRC}. Do not edit by hand.
// ${chosen.length} points; pixel coordinates in a ${w} x ${h} image, y down. \`yellow\` is a string of
// 0/1 flags: 1 where the source pixel is the yellow X mark.
export const LOGO = {
  width: ${w},
  height: ${h},
  x: [${xs.join(',')}],
  y: [${ys.join(',')}],
  yellow: '${yellow}',
}
`
writeFileSync(OUT, body)
console.log(`wrote ${OUT}: ${chosen.length} points (cell ${size}), ${yellow.split('1').length - 1} yellow`)
